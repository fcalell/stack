import { execFile } from "node:child_process";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);

// The child ships beside this module, as the same kind of file (`.js` from
// `dist/`, `.ts` when the plugin runs from source).
const CHILD = fileURLToPath(
	new URL(
		`./schema-child${import.meta.url.slice(import.meta.url.lastIndexOf("."))}`,
		import.meta.url,
	),
);

/** The source of `.stack/schema.ts` (null for a project without routes): every procedure of the app's router (the runtime plugins' routes too) with its input as JSON Schema, its kind and its scope key, which the client reads. The router loads in a child node process, so a long-lived `stack dev` never writes a stale schema; a procedure that fails to load or convert fails `generate`, naming its path. */
export async function schemaSource(cwd: string): Promise<string | null> {
	if (
		!existsSync(join(cwd, ".stack/procedure.ts")) ||
		!existsSync(join(cwd, ".stack/worker.ts")) ||
		!existsSync(join(cwd, "src/worker/routes/index.ts"))
	) {
		return null;
	}
	let schema: unknown;
	try {
		const { stdout } = await run(process.execPath, [CHILD, cwd], {
			maxBuffer: 256 * 1024 * 1024,
		});
		schema = JSON.parse(stdout);
	} catch (error) {
		const detail =
			(error as { stderr?: string }).stderr ??
			(error instanceof Error ? error.message : String(error));
		throw new Error(`generate: could not read the router's schema.\n${detail}`);
	}
	return `// Generated by \`stack generate\`: each procedure's input as JSON Schema, its kind and its scope key.\nexport const SCHEMA = ${JSON.stringify(schema, null, "\t")} as const;\n`;
}
