import { posix } from "node:path";
import type { ContributionCtx } from "@fcalell/cli";
import { z } from "zod";

// A client-only app (web or native) names the stack app it talks to by its
// path. Everything it needs of that app is a file the app's own `stack
// generate` wrote under its `.stack/`.
export const SERVER_SCHEMA = ".stack/schema.ts";
export const SERVER_MANIFEST = ".stack/server.json";
const SERVER_ROUTER_TYPES = ".stack/types/.stack/worker.d.ts";

// What the server app tells its clients beyond its procedures. `auth` is
// whether it has `auth()`, which decides whether a client app stands the
// sign-in provider.
export const serverManifestSchema = z.object({ auth: z.boolean() });
export type ServerManifest = z.infer<typeof serverManifestSchema>;

type FileCtx = Pick<ContributionCtx, "fileExists" | "readFile">;

export const serverRoot = (server: string): string => posix.normalize(server);

/** Reads a file the server app generated, or fails naming what to run there. */
export async function readServerFile(
	ctx: FileCtx,
	server: string,
	file: string,
): Promise<string> {
	const path = posix.join(serverRoot(server), file);
	if (!(await ctx.fileExists(path))) {
		throw new Error(
			`api: \`server: "${server}"\` has no ${file}. Run \`stack generate\` in ${serverRoot(server)} first.`,
		);
	}
	return ctx.readFile(path);
}

export async function readServerManifest(
	ctx: FileCtx,
	server: string,
): Promise<ServerManifest> {
	const text = await readServerFile(ctx, server, SERVER_MANIFEST);
	const parsed = serverManifestSchema.safeParse(JSON.parse(text));
	if (!parsed.success) {
		throw new Error(
			`api: ${posix.join(serverRoot(server), SERVER_MANIFEST)} is not a server manifest (${parsed.error.message}). Run \`stack generate\` in ${serverRoot(server)} again.`,
		);
	}
	return parsed.data;
}

/** The checks a client app passes at generate time: the server app generated everything the client reads, including the router's declaration. */
export async function checkServer(ctx: FileCtx, server: string): Promise<void> {
	await readServerManifest(ctx, server);
	for (const file of [SERVER_SCHEMA, SERVER_ROUTER_TYPES]) {
		if (!(await ctx.fileExists(posix.join(serverRoot(server), file)))) {
			throw new Error(
				`api: \`server: "${server}"\` has no ${file}. Run \`stack generate\` in ${serverRoot(server)} first.`,
			);
		}
	}
}

/** `.stack/server.ts` of a client app: the server's `AppRouter` type, re-exported type-only from the declaration the server's `tsc -b` emits, so no server code enters the bundle and the app never type-checks the server's sources. */
export function serverTypesSource(server: string): string {
	return [
		"// Generated by @fcalell/plugin-api. Do not edit.",
		`export type { AppRouter } from ${JSON.stringify(`../${serverRoot(server)}/.stack/types/.stack/worker`)};`,
		"",
	].join("\n");
}
